#!/usr/bin/env python3
"""Rasterize Inter (SIL OFL 1.1) into a small glyph atlas used to draw the menu images.
Usage: python3 swiftbar/tools/gen_fontatlas.py   (needs Pillow and the Inter fonts)
Writes swiftbar/.config/swiftbar/lib/fontatlas.ts"""
import base64, json, zlib
from PIL import Image, ImageDraw, ImageFont

FONTS = {"reg": "/usr/share/fonts/opentype/inter/Inter-Regular.otf", "semi": "/usr/share/fonts/opentype/inter/Inter-SemiBold.otf"}
SETS = {"reg26": ("reg", 26), "semi26": ("semi", 26), "reg22": ("reg", 22), "semi22": ("semi", 22)}
CHARS = [chr(c) for c in range(32, 127)] + ["·", "↻", "●", "…"]

atlas = {}
for name, (f, size) in SETS.items():
    font = ImageFont.truetype(FONTS[f], size)
    asc, desc = font.getmetrics()
    g = {}
    for ch in CHARS:
        adv = round(font.getlength(ch))
        bbox = font.getbbox(ch)
        if ch == " " or bbox[2] <= bbox[0]:
            g[ch] = {"adv": adv, "w": 0, "h": 0, "bx": 0, "by": 0, "d": ""}
            continue
        w, h = bbox[2] - bbox[0], bbox[3] - bbox[1]
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((-bbox[0], -bbox[1]), ch, font=font, fill=255)
        g[ch] = {"adv": adv, "w": w, "h": h, "bx": bbox[0], "by": bbox[1], "d": base64.b64encode(im.tobytes()).decode()}
    atlas[name] = {"asc": asc, "desc": desc, "glyphs": g}

blob = base64.b64encode(zlib.compress(json.dumps(atlas, separators=(",", ":")).encode(), 9)).decode()
open("swiftbar/.config/swiftbar/lib/fontatlas.ts", "w").write(
    "// Generated by swiftbar/tools/gen_fontatlas.py from Inter (SIL Open Font License 1.1). Do not edit.\n"
    f'export const ATLAS_B64 = "{blob}";\n')
print(len(blob) // 1024, "KB")
